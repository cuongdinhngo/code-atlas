def render_agent_brief() -> str:
    """Agent brief selected from the live ``which_tool`` map (tasks 266 / 300)."""
    lines_by_tool = recognition_lines_by_tool()
    missing = [
        tool
        for _title, tools in OCCASIONS
        for tool in tools
        if tool not in lines_by_tool
    ]
    if missing:
        raise RuntimeError(f"which_tool map missing tools named by OCCASIONS: {missing}")
    out = [
        BRIEF_HEADING,
        "",
        "Generated by `scripts/gen_skill.py` from the `which_tool` recognition map.",
        "Do not edit by hand — regenerate with",
        "`python scripts/gen_skill.py --write-agent-brief <repo>`.",
        "",
    ]
    for title, tools in OCCASIONS:
        out.append(f"### {title}")
        out.append("")
        for tool in tools:
            out.append(lines_by_tool[tool])
        out.append("")
    out.extend(USAGE_RULES)
    return "\n".join(out)


GENERATED[AGENT_BRIEF_PATH] = render_agent_brief


def claude_md_lacks_agents_import(repo_root: Path) -> bool:
    """True when CLAUDE.md exists and neither memory file already imports AGENTS.md (270)."""
    root = repo_root.resolve()
    if not (root / "CLAUDE.md").is_file():
        return False
    # The offer names either file, so either one satisfying it must silence the offer.
    return not any(
        (root / name).is_file()
        and AGENTS_IMPORT_LINE in (root / name).read_text(encoding="utf-8")
        for name in CLAUDE_MEMORY_FILES
    )


def write_agent_brief(repo_root: Path) -> Path:
    """Install the brief into repo_root/AGENTS.md idempotently (266); offer Claude import (270)."""
    root = repo_root.resolve()
    path = root / "AGENTS.md"
    body = render_agent_brief().rstrip() + "\n"
    block = f"{BRIEF_BEGIN}\n{body}{BRIEF_END}\n"
    if path.is_file():
        text = path.read_text(encoding="utf-8")
        if BRIEF_BEGIN in text and BRIEF_END in text:
            before, rest = text.split(BRIEF_BEGIN, 1)
            _old, after = rest.split(BRIEF_END, 1)
            text = before + block + after.lstrip("\n")
        else:
            sep = "" if text.endswith("\n") or not text else "\n"
            text = text + sep + "\n" + block
    else:
        text = block
    path.write_text(text, encoding="utf-8")
    # Print, never write CLAUDE.md (PLAN §19 / 270).
    if claude_md_lacks_agents_import(root):
        print(CLAUDE_IMPORT_OFFER)
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="rewrite the generated files in place")
    parser.add_argument(
        "--write-agent-brief",
        metavar="REPO",
        help="write/replace the AGENTS.md brief section in REPO (task 266)",
    )
    args = parser.parse_args(argv)
    if args.write_agent_brief:
        dest = write_agent_brief(Path(args.write_agent_brief))
        print(f"wrote {dest}")
        return 0
    stale = []
    for path, render in GENERATED.items():
        wanted = render()
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(wanted, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")
        elif not path.is_file() or path.read_text(encoding="utf-8") != wanted:
            stale.append(path.relative_to(REPO).as_posix())
    for name in stale:
        print(f"stale: {name} — run `python scripts/gen_skill.py --write`", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
