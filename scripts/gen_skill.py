def recognition_lines_by_tool() -> dict[str, str]:
    """First ``which_tool`` line naming each tool — the one parse of that map (R6.7)."""
    lines_by_tool: dict[str, str] = {}
    for line in recognition_map():
        # "- question -> tool." or "- question -> tool (note)."
        if "->" not in line:
            continue
        rhs = line.split("->", 1)[1].strip()
        lines_by_tool.setdefault(rhs.split()[0].rstrip("."), line)
    return lines_by_tool


