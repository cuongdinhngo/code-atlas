# An adapter announces its suffixes in its entry file; the handshake sends this same literal.
# Reading it statically is what lets a guard check coverage without starting a subprocess.
_EXT_DECL = re.compile(r"""extensions['"]?\s*(?::|=>)\s*[\[(]([^\])]*)[\])]""")
_EXT_ITEM = re.compile(r"""['"](\.[A-Za-z0-9_]+)['"]""")


class _PromptRecorder:
    """Stands in for the FastMCP server so `prompts.register` can be read, not imported.

    `which_tool` is a closure inside `register`, and `register` only ever calls
    `server.prompt(name=…)(fn)` — so one method is the whole surface it needs.
    """

    def __init__(self) -> None:
        self.prompts: dict[str, Callable[..., str]] = {}

    def prompt(self, name: str) -> Callable[[Callable[..., str]], Callable[..., str]]:
        def keep(fn: Callable[..., str]) -> Callable[..., str]:
            self.prompts[name] = fn
            return fn

        return keep


def recognition_map() -> list[str]:
    """The `which_tool` map, as its `- question -> tool.` lines, in the order the prompt emits."""
    recorder = _PromptRecorder()
    prompts.register(recorder)  # type: ignore[arg-type]
    body = recorder.prompts[prompts.WHICH_TOOL]()
    return [line for line in body.splitlines() if line.startswith("- ")]


def declared_extensions(adapters_dir: Path | None = None) -> dict[str, tuple[str, ...]]:
    """Each shipped adapter's declared suffixes, read from its own entry file.

    An adapter whose declaration does not parse maps to `()` — so it reads as uncovered and turns
    the coverage guard red, rather than passing quietly.
    """
    root = ADAPTERS_DIR if adapters_dir is None else adapters_dir
    found: dict[str, tuple[str, ...]] = {}
    for name in shipped_adapters(root):
        found[name] = ()
        for path in sorted(p for p in (root / name).iterdir() if p.is_file()):
            try:
                text = path.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                continue
            match = _EXT_DECL.search(text)
            if match:
                found[name] = tuple(_EXT_ITEM.findall(match.group(1)))
                break
    return found


def render_skill() -> str:
    """`SKILL.md` — the map plus the roster, and nothing that could disagree with the server."""
    lines = [
        "---",
        "name: code-atlas",
        "description: >-",
        "  Route a question about an unfamiliar codebase to the right code-atlas MCP tool —",
        "  search, read, callers, references, impact, architecture, onboarding. Use when the",
        "  code-atlas server is connected and you are deciding which of its tools answers the",
        "  question in front of you.",
        "---",
        "",
        "# code-atlas — which tool answers which question",
        "",
        f"Generated by `scripts/gen_skill.py` from the {len(TOOL_NAMES)} tools the server",
        "registers and from the `which_tool` recognition map. Do not edit by hand: a drift guard",
        "compares this file to its source, so a hand edit is a red test, not a quiet",
        "disagreement.",
        "",
        "## Recognition map",
        "",
    ]
    lines.extend(recognition_map())
    lines.extend(
        [
            "",
            "Call `get_index_status` first whenever you are unsure the index is current.",
            "",
            "## The served surface",
            "",
        ]
    )
    lines.extend(f"{n}. `{name}`" for n, name in enumerate(TOOL_NAMES, start=1))
    lines.extend(
        [
            "",
            "## What this skill is not",
            "",
            "It carries the map, never a second set of tool descriptions — the descriptions the",
            "client shows you are the ones that route, and a copy here could disagree with them.",
            "It holds no live state either: index freshness, symbol counts and open work are what",
            "the tools are for, and a number frozen into this file would be a wrong answer rather",
            "than a stale one.",
            "",
        ]
    )
    return "\n".join(lines)


def _suffix_filter(*tools: str) -> str:
    """A hook `if` filter over every shipped adapter's declared suffixes, for the named tools."""
    suffixes = [suffix for _, group in sorted(declared_extensions().items()) for suffix in group]
    return "|".join(f"{tool}(*{s})" for s in suffixes for tool in tools)


def render_claude_code_snippet() -> str:
    """Every Claude Code hook code-atlas offers: the edit poke (036), the signal (099) and the
    session-boundary state line (322) — `SessionStart` covers the post-compaction delivery.

    099 shipped the signal wired for Codex only; 240 is the guard-less drift that let that stand.
    `Read` belongs at PostToolUse (the line rides the result); `Write` at PreToolUse, because the
    create-vs-edit test is whether the path exists yet — see `docs/TOOLS.md`.
    """
    return json.dumps({"hooks": _claude_code_hooks(lambda name: name)}, indent=2) + "\n"


def _claude_code_hooks(command: Callable[[str], str]) -> dict[str, Any]:
    """The one hook table: the snippet names each console script, the plugin gates it (344)."""
    return {
        "PostToolUse": [
            {
                "matcher": "Edit|Write",
                "hooks": [
                    {
                        "type": "command",
                        "command": command("code-atlas-poke"),
                        "if": _suffix_filter("Edit", "Write"),
                        "async": True,
                        "timeout": 60,
                    }
                ],
            },
            {
                "matcher": "Read",
                "hooks": [
                    {
                        "type": "command",
                        "command": command("code-atlas-signal"),
                        "if": _suffix_filter("Read"),
                        "timeout": 10,
                    }
                ],
            },
        ],
        "PreToolUse": [
            {
                "matcher": "Write",
                "hooks": [
                    {
                        "type": "command",
                        "command": command("code-atlas-signal"),
                        "if": _suffix_filter("Write"),
                        "timeout": 10,
                    }
                ],
            }
        ],
        "SessionStart": [
            {"hooks": [{"type": "command", "command": command("code-atlas-state"), "timeout": 10}]}
        ],
        "PreCompact": [
            {"hooks": [{"type": "command", "command": command("code-atlas-state"), "timeout": 10}]}
        ],
    }




def render_plugin_hooks() -> str:
    """The snippet's hooks, each gated on the index, plus a background refresh at start (344)."""
    hooks = _claude_code_hooks(lambda name: PLUGIN_GATE + name)
    refresh = {"type": "command", "command": PLUGIN_GATE + "code-atlas-refresh"}
    hooks["SessionStart"].append({"hooks": [{**refresh, "async": True, "timeout": 600}]})
    return json.dumps({"hooks": hooks}, indent=2) + "\n"


def _package() -> dict[str, Any]:
    project: dict[str, Any] = tomllib.loads((REPO / "pyproject.toml").read_text(encoding="utf-8"))
    return dict(project["project"])


def render_plugin_manifest() -> str:
    """Name, version and description from the package, so the plugin never lags it (R6.7)."""
    package = _package()
    manifest = {
        "name": package["name"],
        "version": package["version"],
        "description": package["description"],
        "author": {"name": "cuongdinhngo"},
        "homepage": REPOSITORY_URL,
        "repository": REPOSITORY_URL,
        "license": package["license"]["text"],
    }
    return json.dumps(manifest, indent=2) + "\n"


def render_plugin_mcp() -> str:
    """The server by its console-script name; Claude Code starts it in the project dir (344)."""
    return json.dumps({"mcpServers": {"code-atlas": {"command": "code-atlas"}}}, indent=2) + "\n"


def render_marketplace() -> str:
    """This repo as a one-plugin marketplace: `/plugin marketplace add cuongdinhngo/code-atlas`."""
    package = _package()
    plugin = {
        "name": package["name"],
        "source": "./" + PLUGIN_DIR.relative_to(REPO).as_posix(),
        "description": package["description"],
        "version": package["version"],
    }
    market = {
        "name": package["name"],
        "owner": {"name": "cuongdinhngo"},
        "metadata": {"description": "code-atlas as a Claude Code plugin: server, hooks and skill."},
        "plugins": [plugin],
    }
    return json.dumps(market, indent=2) + "\n"


